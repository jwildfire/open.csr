export function buildQualitySummary({ modules, rootDir }) {
  const suites = new Set();
  let totalTests = 0;
  let passedTests = 0;
  let totalRequirements = 0;
  let matrices = 0;
  const referenced = new Set();
  const known = new Set();

  for (const module of modules) {
    const evidence = loadEvidence(rootDir, module.module);
    const requirements = loadRequirements(rootDir, module.module);
    if (requirements.matrix && Object.keys(requirements.requirements).length) matrices += 1;
    for (const id of Object.keys(requirements.requirements)) known.add(id);
    if (evidence) {
      for (const rec of evidence.records || []) {
        suites.add(rec.suite);
        for (const id of rec.requirementIds || []) referenced.add(id);
      }
    }
  }
  // Requirements are counted once across the whole repo — several displays share
  // displays.md, so summing per-module extracts would multiply-count them.
  totalRequirements = known.size;

  // Shared records appear in several sets; count each distinct test once.
  const seenTests = new Set();
  let pendingTests = 0;
  for (const module of modules) {
    const evidence = loadEvidence(rootDir, module.module);
    for (const rec of (evidence && evidence.records) || []) {
      const key = `${rec.suite}|${rec.title}`;
      if (seenTests.has(key)) continue;
      seenTests.add(key);
      totalTests += 1;
      if (rec.passed) passedTests += 1;
      else if (rec.suite === 'text-review') pendingTests += 1;
    }
  }

  const coverage = resolveRequirementCoverage({
    requirements: Object.fromEntries([...known].map((id) => [id, true])),
    referenced: [...referenced],
    known
  });

  return {
    suites: [...suites].sort(),
    totalTests,
    passedTests,
    pendingTests,
    totalRequirements,
    matrices,
    coverage
  };
}

