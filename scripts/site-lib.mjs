export function escapeHtml(text) {
  return String(text ?? '').replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]
  );
}

export function slugify(text) {
  return (
    String(text ?? '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'section'
  );
}

// Inline markdown for text that came out of a table cell — requirement prose
// routinely names `variables` and `functions()` in code spans. HTML is escaped
// first, so only this small, known subset can produce markup.
export function mdInline(text) {
  return escapeHtml(text)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
}

// Markdown → HTML for docs pages and text-block bodies. `marked` is vendored in
// node_modules; nothing is fetched at build or view time.
export function renderMarkdown(markdown) {
  return marked.parse(String(markdown ?? ''), { async: false });
}

// Give h2/h3 stable ids so the docs pages can carry a table of contents.
export function withHeadingIds(html) {
  const seen = new Map();
  return String(html).replace(/<h([23])>([\s\S]*?)<\/h\1>/g, (_, level, inner) => {
    const base = slugify(inner.replace(/<[^>]+>/g, ''));
    const count = seen.get(base) || 0;
    seen.set(base, count + 1);
    const id = count ? `${base}-${count + 1}` : base;
    return `<h${level} id="${id}">${inner}</h${level}>`;
  });
}

export function extractHeadings(html) {
  return [...String(html).matchAll(/<h([23]) id="([^"]+)">([\s\S]*?)<\/h\1>/g)].map((m) => ({
    level: Number(m[1]),
    id: m[2],
    text: m[3].replace(/<[^>]+>/g, '').trim()
  }));
}

// Embedded HTML (a gt table, an assembled CSR fragment) is generated by our own
// pipeline but still gets neutered before it goes on the page: scripts removed,
// external stylesheets/imports dropped, document wrapper unwrapped. That keeps
// the "no external resource, no runtime network" guarantee true even for HTML
// this build did not author.
export function sanitizeEmbeddedHtml(html) {
  let out = String(html ?? '');
  const body = out.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  if (body) out = body[1];
  return out
    .replace(/<!DOCTYPE[^>]*>/gi, '')
    .replace(/<\/?(?:html|head|body)[^>]*>/gi, '')
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<link[^>]*href=["']https?:[^"']*["'][^>]*>/gi, '')
    .replace(/@import\s+url\(["']?https?:[^)]*\)\s*;?/gi, '')
    .replace(/\son[a-z]+="[^"]*"/gi, '');
}

const CODE_LANG = { yaml: 'yaml', yml: 'yaml', json: 'json', r: 'r', md: 'markdown' };

export function codeBlock(text, file = '') {
  const lang = CODE_LANG[path.extname(file).slice(1).toLowerCase()] || '';
  return (
    `<figure class="code">${file ? `<figcaption>${escapeHtml(file)}</figcaption>` : ''}` +
    `<pre><code class="lang-${lang}">${escapeHtml(text)}</code></pre></figure>`
  );
}

export function chip(label, kind = 'neutral', title = '') {
  return (
    `<span class="chip chip-${kind}"${title ? ` title="${escapeHtml(title)}"` : ''}>` +
    `${escapeHtml(label)}</span>`
  );
}

export function empty(message) {
  return `<p class="empty">${escapeHtml(message)}</p>`;
}

function pct(numerator, denominator) {
  if (!denominator) return '—';
  return `${Math.round((numerator / denominator) * 100)}%`;
}

