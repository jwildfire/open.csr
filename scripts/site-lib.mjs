function readText(file) {
  try {
    return existsSync(file) ? readFileSync(file, 'utf8') : null;
  } catch {
    return null;
  }
}

function readJsonFile(file) {
  const text = readText(file);
  if (text === null) return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

function readYamlFile(file) {
  const text = readText(file);
  if (text === null) return null;
  try {
    return yaml.load(text);
  } catch {
    return null;
  }
}

function listDirs(dir) {
  if (!existsSync(dir)) return [];
  try {
    return readdirSync(dir).filter((entry) => statSync(path.join(dir, entry)).isDirectory());
  } catch {
    return [];
  }
}

export function sha256(text) {
  return `sha256:${createHash('sha256').update(String(text)).digest('hex')}`;
}

// `outputs/<slug>/current.json` points at the live iteration (contracts §1).
// Its shape is the R pipeline's business, so accept the plausible spellings and
// fall back to the highest vNNN directory present.
export function pickCurrentVersion(versions, pointer) {
  const ordered = [...versions].sort();
  const candidate =
    typeof pointer === 'string'
      ? pointer
      : pointer && (pointer.version || pointer.current || pointer.iteration || pointer.v);
  if (candidate && ordered.includes(String(candidate))) return String(candidate);
  return ordered.length ? ordered[ordered.length - 1] : null;
}

// Everything on disk for one display: its specs, its iteration ledger, and each
// saved iteration's manifest/ARD/rendered table.
export function loadDisplayOutputs(rootDir, slug) {
  const specDir = path.join(rootDir, 'library', 'tfl', slug);
  const outDir = path.join(rootDir, 'outputs', slug);
  const relative = (file) => path.relative(rootDir, file).replaceAll('\\', '/');

  const specFiles = {
    analysis: path.join(specDir, 'analysis.yaml'),
    display: path.join(specDir, 'display.yaml'),
    custom: path.join(specDir, 'custom.R'),
    iterations: path.join(specDir, 'iterations.yaml')
  };
  const specs = Object.fromEntries(
    Object.entries(specFiles).map(([key, file]) => [
      key,
      existsSync(file) ? { file: relative(file), text: readText(file) } : null
    ])
  );

  const versionDirs = listDirs(outDir).filter((entry) => /^v\d+$/.test(entry));
  const versions = versionDirs.sort().map((version) => {
    const dir = path.join(outDir, version);
    const ardPath = path.join(dir, 'ard.json');
    const tablePath = path.join(dir, 'table.html');
    const manifest = readJsonFile(path.join(dir, 'manifest.json'));
    const ardText = readText(ardPath);
    // Submission artifacts (#129 A): the RTF the pipeline wrote beside each
    // rendered variant, named by the manifest rather than guessed at, so a
    // renaming in the pipeline surfaces here as a missing artifact instead of a
    // silently wrong link.
    const artifacts = Object.entries(manifest?.variants || {})
      .filter(([, entry]) => entry && entry.rtf)
      .map(([variant, entry]) => ({
        variant,
        format: 'rtf',
        file: relative(path.join(dir, entry.rtf)),
        hash: entry.rtf_hash || null,
        exists: existsSync(path.join(dir, entry.rtf))
      }));
    return {
      version,
      dir: relative(dir),
      manifest,
      ard: ardText ? safeJson(ardText) : null,
      ardFile: ardText ? relative(ardPath) : null,
      ardHash: ardText ? sha256(ardText) : null,
      tableFile: existsSync(tablePath) ? relative(tablePath) : null,
      tableHtml: readText(tablePath),
      artifacts
    };
  });

  const currentVersion = pickCurrentVersion(
    versions.map((v) => v.version),
    readJsonFile(path.join(outDir, 'current.json'))
  );
  const current = versions.find((v) => v.version === currentVersion) || null;

  return {
    slug,
    specDir: existsSync(specDir) ? relative(specDir) : null,
    outDir: existsSync(outDir) ? relative(outDir) : null,
    displayFile: specs.display ? specs.display.file : null,
    analysisFile: specs.analysis ? specs.analysis.file : null,
    specs,
    iterations: normalizeIterations(readYamlFile(specFiles.iterations), versions),
    versions,
    current
  };
}

function safeJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

// The iteration ledger: `iterations.yaml` when the library has one, otherwise
// reconstructed from the output manifests, so the timeline renders as soon as
// the pipeline has written a single iteration.
export function normalizeIterations(ledger, versions = []) {
  const fromLedger = Array.isArray(ledger)
    ? ledger
    : (ledger && (ledger.iterations || ledger.versions)) || [];
  const byVersion = new Map();
  for (const entry of fromLedger) {
    const version = String(entry.version || entry.v || entry.id || '').trim();
    if (!version) continue;
    byVersion.set(version, {
      version,
      date: entry.date || entry.at || entry.when || null,
      actor: entry.actor || entry.by || entry.author || null,
      request: entry.request || entry.change_request || entry.change || entry.summary || null,
      commit: entry.commit || entry.git_commit || null,
      notes: entry.notes || null
    });
  }
  for (const output of versions) {
    const manifest = output.manifest || {};
    const existing = byVersion.get(output.version) || { version: output.version };
    byVersion.set(output.version, {
      ...existing,
      date: existing.date || manifest.date || manifest.created || manifest.generated || null,
      actor: existing.actor || manifest.actor || manifest.by || null,
      request: existing.request || manifest.request || manifest.reason || null,
      commit: existing.commit || manifest.commit || manifest.git_commit || null,
      hasOutput: true
    });
  }
  return [...byVersion.values()].sort((a, b) => a.version.localeCompare(b.version));
}

// Registry displays plus any display directory the registry does not know
// about. Slug drift between the registry and the pipeline therefore surfaces on
// the site as an unregistered card instead of silently disappearing.
export function loadDisplays(rootDir, config) {
  const registered = (config.displays || []).map((entry) => ({
    ...entry,
    module: entry.module || entry.slug,
    registered: true
  }));
  const known = new Set(registered.map((entry) => entry.slug));
  // A directory under outputs/ is only a display if it holds display iterations.
  // outputs/ also carries the values store (#129 B), and a store is not a table:
  // discovery keys on the vNNN shape the pipeline writes rather than on presence.
  const hasIterations = (slug) =>
    listDirs(path.join(rootDir, 'outputs', slug)).some((entry) => /^v\d+$/.test(entry));
  const discovered = [
    ...new Set([
      ...listDirs(path.join(rootDir, 'outputs')).filter(hasIterations),
      ...listDirs(path.join(rootDir, 'library', 'tfl'))
    ])
  ]
    .filter((slug) => !known.has(slug) && !slug.startsWith('.'))
    .sort()
    .map((slug) => ({
      module: slug,
      slug,
      title: slug,
      type: slug.startsWith('l-') ? 'listing' : slug.startsWith('f-') ? 'figure' : 'table',
      matrix: 'displays.md',
      registered: false,
      blurb: 'Discovered on disk but not present in site/config.json.'
    }));

  return [...registered, ...discovered].map((entry) => {
    const outputs = loadDisplayOutputs(rootDir, entry.slug);
    const hasEvidence = existsSync(
      path.join(rootDir, 'docs', 'evidence', entry.module, 'evidence.json')
    );
    return { ...entry, outputs, status: deriveStatus(entry, { outputs, hasEvidence }) };
  });
}

// contracts §9: status is planned | built | evidenced. The registry declares an
// intent; the filesystem decides. A display is `built` once an iteration with an
// ARD exists and `evidenced` once its evidence set does.
export function deriveStatus(entry, { outputs = null, hasEvidence = false, exists = null } = {}) {
  const built =
    exists !== null ? exists : !!(outputs && outputs.current && outputs.current.ardFile);
  if (built && hasEvidence) return 'evidenced';
  if (built) return 'built';
  return entry && entry.status === 'evidenced' ? 'planned' : entry?.status || 'planned';
}

export const BINDING_RE = /\{\{ard:([^}]+)\}\}/g;

// Text blocks: registry entries merged with everything in library/text/, parsed
// with gray-matter per contracts §6.
export function loadTextBlocks(rootDir, config) {
  const dir = path.join(rootDir, 'library', 'text');
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md')).sort() : [];
  const byId = new Map();

  for (const entry of config.textBlocks || []) {
    byId.set(entry.id, { ...entry, file: `library/text/${entry.id}.md`, exists: false });
  }
  for (const file of files) {
    const full = path.join(dir, file);
    const raw = readText(full);
    if (raw === null) continue;
    let parsed = { data: {}, content: raw };
    try {
      parsed = matter(raw);
    } catch {
      /* malformed frontmatter — fall through to the raw body */
    }
    const data = parsed.data || {};
    const id = data.id || path.basename(file, '.md');
    const body = parsed.content || '';
    const bindings = [...body.matchAll(BINDING_RE)].map((m) => m[1].trim());
    byId.set(id, {
      ...(byId.get(id) || {}),
      id,
      file: `library/text/${file}`,
      exists: true,
      title: data.title || byId.get(id)?.title || id,
      e3Section: data.e3_section || data.e3Section || byId.get(id)?.e3Section || null,
      tier: data.tier || byId.get(id)?.tier || 'boilerplate',
      displays: data.displays || byId.get(id)?.displays || [],
      approval: data.approval || null,
      provenance: data.provenance || null,
      requirements: data.requirements || [],
      allowDigits: data.allow_digits || data.allowDigits || [],
      body,
      bindings: [...new Set(bindings)]
    });
  }

  return [...byId.values()]
    .map((block) => ({
      ...block,
      bindings: block.bindings || [],
      status: deriveStatus(block, {
        exists: !!block.exists,
        hasEvidence: block.approval?.state === 'approved'
      })
    }))
    .sort((a, b) => String(a.e3Section || '').localeCompare(String(b.e3Section || '')) ||
      a.id.localeCompare(b.id));
}

