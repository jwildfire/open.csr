// contracts §5: `<display>:<analysis>:<stat_name>[;group=<level>][;variable_level=<level>]`
export function parseBinding(address) {
  const [head, ...qualifiers] = String(address || '').split(';');
  const [display, analysis, statName] = head.split(':').map((part) => (part || '').trim());
  const filters = {};
  for (const qualifier of qualifiers) {
    const index = qualifier.indexOf('=');
    if (index < 0) continue;
    filters[qualifier.slice(0, index).trim()] = qualifier.slice(index + 1).trim();
  }
  return { address: String(address || '').trim(), display, analysis, statName, filters };
}

function rowGroups(row) {
  return Object.entries(row)
    .filter(([key]) => /^group\d+_level$/.test(key))
    .map(([, value]) => value);
}

// Resolve a binding against a display's ard.json (contracts §5). Returns the
// matched row and its value, or a reason the binding did not resolve — an
// orphaned binding is a loud build-time fact, not a silently stale sentence.
export function resolveBinding(address, ardsBySlug) {
  const parsed = parseBinding(address);
  const ard = ardsBySlug[parsed.display];
  if (!ard) return { ...parsed, resolved: false, reason: `no ARD for display "${parsed.display}"` };
  const rows = (ard.rows || []).filter((row) => {
    if (parsed.analysis && row.analysis !== parsed.analysis) return false;
    if (parsed.statName && row.stat_name !== parsed.statName) return false;
    if (parsed.filters.group && !rowGroups(row).includes(parsed.filters.group)) return false;
    if (
      parsed.filters.variable_level &&
      row.variable_level !== parsed.filters.variable_level
    )
      return false;
    if (parsed.filters.variable && row.variable !== parsed.filters.variable) return false;
    return true;
  });
  if (rows.length !== 1) {
    return {
      ...parsed,
      resolved: false,
      matches: rows.length,
      reason: rows.length ? `${rows.length} ARD rows match (must be exactly 1)` : 'no ARD row matches'
    };
  }
  return { ...parsed, resolved: true, matches: 1, row: rows[0], value: rows[0].stat };
}

export function formatStat(value, { scale = null, digits = null } = {}) {
  if (value === null || value === undefined) return '—';
  if (Array.isArray(value)) return value.join(', ');
  if (typeof value === 'number') {
    // `scale=` and `digits=` are presentation qualifiers on the binding address:
    // proportions are stored as proportions in the ARD and become percentages in
    // prose, which keeps the ARD the single numeric source of truth.
    const scaled = scale === null ? value : value * Number(scale);
    if (!Number.isFinite(scaled)) return String(value);
    return digits === null ? String(scaled) : scaled.toFixed(Number(digits));
  }
  return String(value);
}

// The build-time join every trace panel reads: display → its data, ARD,
// display spec, iteration and evidence page.
export function buildTraceIndex(displays) {
  const index = {};
  for (const display of displays) {
    const current = display.outputs?.current || null;
    const provenance = (current && current.ard && current.ard.provenance) || {};
    index[display.slug] = {
      slug: display.slug,
      title: display.title || display.slug,
      regulatoryId: display.regulatoryId || null,
      status: display.status,
      datasets:
        (Array.isArray(provenance.data) && provenance.data.map((d) => d.dataset)) ||
        display.datasets ||
        [],
      dataHashes: Object.fromEntries(
        (Array.isArray(provenance.data) ? provenance.data : [])
          .filter((d) => d.dataset)
          .map((d) => [d.dataset, d.hash || null])
      ),
      analysisFile: display.outputs?.analysisFile || null,
      displayFile: display.outputs?.displayFile || null,
      ardFile: current?.ardFile || null,
      ardHash: current?.ardHash || null,
      specHash: provenance.spec_hash || null,
      commit: provenance.git_commit || current?.manifest?.commit || null,
      iteration: current?.version || null,
      iterations: (display.outputs?.iterations || []).length,
      page: `../gallery/${display.slug}.html`,
      evidence: `../quality/${display.module}.html`
    };
  }
  return index;
}

