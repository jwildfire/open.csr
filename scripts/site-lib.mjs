// Static-site generators for open.csr (#1). Pure-ish functions that
// scripts/site.mjs assembles into site/_build/. Plain Node, no framework, no
// network, no CDN — the build is a function of the repo tree, and every
// internal URL is relative so one build serves the site root and any
// subdirectory mount.
//
// Two rules run through the whole file:
//
//   1. DEGRADE, NEVER CRASH. The R pipeline, the assembler, and the libraries
//      are built in parallel with this site. Every loader tolerates a missing
//      or half-written input and every renderer has a "not yet generated"
//      state, so the site publishes from day one and fills in as work lands.
//   2. TRACEABILITY IS THE PRODUCT. Displays, ARDs, text blocks and sentences
//      are joined at build time into one index, which is what makes the CSR
//      Reader's trace panel a lookup rather than a promise.

