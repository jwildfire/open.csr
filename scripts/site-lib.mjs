// Rewrite the links inside a rendered doc so cross-references between the design
// docs and the research sections point at the built pages, and everything else
// points at the repository.
export function rewriteDocLinks(html, { docPages, repoUrl, sourceFile }) {
  return String(html).replace(/(href|src)="([^"]+)"/g, (whole, attr, target) => {
    if (/^(https?:|mailto:|data:|#)/.test(target)) return whole;
    const [pathPart, hash = ''] = target.split('#');
    if (!pathPart) return whole;
    const resolved = path
      .posix
      .normalize(path.posix.join(path.posix.dirname(sourceFile), pathPart))
      .replace(/^\.\//, '');
    const page = docPages.get(resolved);
    if (page) return `${attr}="${page}${hash ? `#${hash}` : ''}"`;
    return `${attr}="${repoUrl}/blob/main/${resolved}${hash ? `#${hash}` : ''}"`;
  });
}

export function renderDocsIndex({ config, docs }) {
  const groups = new Map();
  for (const doc of docs) {
    const group = doc.group || 'Documents';
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(doc);
  }
  const sections = [...groups]
    .map(
      ([group, entries]) =>
        `<section class="panel"><h2>${escapeHtml(group)}</h2><ul class="doc-list">` +
        entries
          .map(
            (doc) =>
              `<li><a href="${escapeHtml(doc.page)}">${escapeHtml(doc.title)}</a>` +
              `<span class="mono sub">${escapeHtml(doc.file)}</span>` +
              (doc.exists ? '' : chip('missing', 'warn')) +
              `</li>`
          )
          .join('') +
        `</ul></section>`
    )
    .join('');

  return [
    pageHeader(
      'Design & Research',
      'How open.csr was designed',
      'The design document and the interface contracts every component builds against, plus the ' +
        'landscape research that produced them — rendered from the repository, not restated.'
    ),
    sections || empty('No documents registered.'),
    `<p class="sub">Source of record: <a href="${escapeHtml(config.repoUrl)}">${escapeHtml(
      config.repoUrl
    )}</a></p>`
  ].join('\n');
}

export function renderDocPage({ doc, html }) {
  const withIds = withHeadingIds(html);
  const headings = extractHeadings(withIds).filter((h) => h.level === 2);
  const toc = headings.length
    ? `<nav class="doc-toc" aria-label="On this page"><h2>On this page</h2><ol>` +
      headings
        .map((h) => `<li><a href="#${escapeHtml(h.id)}">${escapeHtml(h.text)}</a></li>`)
        .join('') +
      `</ol></nav>`
    : '';
  return [
    `<p class="crumb"><a href="index.html">Design &amp; Research</a> / ` +
      `<span class="mono">${escapeHtml(doc.file)}</span></p>`,
    `<div class="doc-layout">${toc}<article class="prose doc">${withIds}</article></div>`
  ].join('\n');
}

