function walkHtmlFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((entry) => {
    const file = path.join(dir, entry);
    if (statSync(file).isDirectory()) return walkHtmlFiles(file);
    return entry.endsWith('.html') ? [file] : [];
  });
}

// Every internal href/src in the emitted site must resolve to an emitted file.
export function validateSiteLinks(siteDir) {
  const errors = [];
  for (const file of walkHtmlFiles(siteDir)) {
    const html = readFileSync(file, 'utf8');
    for (const [, target] of html.matchAll(/(?:href|src)="([^"]*)"/g)) {
      if (/^(https?:|mailto:|data:|#|\/\/)/.test(target)) continue;
      const cleaned = decodeURI(target.split(/[?#]/)[0]);
      if (!cleaned) continue;
      const resolved = path.resolve(path.dirname(file), cleaned);
      if (!existsSync(resolved)) {
        errors.push(`${path.relative(siteDir, file)}: broken internal link "${target}"`);
      }
    }
  }
  return errors;
}

// No external RESOURCE may be referenced: no CDN script, no remote stylesheet,
// no remote font or image. Outbound <a href> links to GitHub are fine — they are
// navigation, not a runtime dependency.
export function validateNoExternalResources(siteDir) {
  const errors = [];
  const patterns = [
    [/<script[^>]+src=["'](https?:|\/\/)[^"']*["']/gi, 'external script'],
    [/<link[^>]+href=["'](https?:|\/\/)[^"']*["']/gi, 'external stylesheet or preload'],
    [/<img[^>]+src=["'](https?:|\/\/)[^"']*["']/gi, 'external image'],
    [/@import\s+url\(["']?(https?:|\/\/)/gi, 'external CSS import'],
    // Any other remote url() — @import hits are removed first so one offending
    // line is reported once, not twice.
    [/url\(["']?(https?:|\/\/)/gi, 'external CSS url()', true]
  ];
  const files = [
    ...walkHtmlFiles(siteDir),
    ...(existsSync(path.join(siteDir, 'site.css')) ? [path.join(siteDir, 'site.css')] : [])
  ];
  for (const file of files) {
    const raw = readFileSync(file, 'utf8');
    for (const [pattern, label, withoutImports] of patterns) {
      const text = withoutImports ? raw.replace(/@import\s+url\([^)]*\)/gi, '') : raw;
      for (const match of text.matchAll(pattern)) {
        errors.push(`${path.relative(siteDir, file)}: ${label} — ${match[0].slice(0, 90)}`);
      }
    }
  }
  return errors;
}
