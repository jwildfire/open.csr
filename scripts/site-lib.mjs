export function renderArdTable(ard, { limit = 250 } = {}) {
  const rows = (ard && ard.rows) || [];
  if (!rows.length) return empty('No ARD rows — this display has not been generated yet.');
  const columns = [
    'analysis',
    ...[...new Set(rows.flatMap((row) => Object.keys(row)))].filter(
      (key) => key !== 'analysis' && key !== 'stat'
    ),
    'stat'
  ].filter((key, index, all) => all.indexOf(key) === index);

  const head = columns.map((col) => `<th>${escapeHtml(col)}</th>`).join('');
  const body = rows
    .slice(0, limit)
    .map((row) => {
      const cells = columns
        .map((col) => {
          const value = row[col];
          const isCondition = col === 'warning' || col === 'error';
          const cls = isCondition && value ? ' class="bad"' : col === 'stat' ? ' class="num"' : '';
          return `<td${cls}>${escapeHtml(formatStat(value ?? null))}</td>`;
        })
        .join('');
      return `<tr>${cells}</tr>`;
    })
    .join('');

  const note =
    rows.length > limit
      ? `<p class="sub">Showing the first ${limit} of ${rows.length} rows — the full ARD is committed ` +
        `beside the display.</p>`
      : `<p class="sub">${rows.length} row${rows.length === 1 ? '' : 's'}, one per computed statistic.</p>`;

  return (
    `<div class="table-tools"><input type="search" class="ard-filter" ` +
    `placeholder="Filter ARD rows…" aria-label="Filter ARD rows"></div>` +
    `<div class="scroll"><table class="data ard-table"><thead><tr>${head}</tr></thead>` +
    `<tbody>${body}</tbody></table></div>${note}`
  );
}

